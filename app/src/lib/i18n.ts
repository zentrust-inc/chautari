import { signal } from '@preact/signals';

export type Lang = 'np' | 'en';
const saved = (() => { try { return localStorage.getItem('wwos.lang') as Lang | null; } catch { return null; } })();
export const lang = signal<Lang>(saved === 'en' ? 'en' : 'np');
export function setLang(l: Lang) {
  lang.value = l;
  document.documentElement.lang = l === 'np' ? 'ne' : 'en';
  try { localStorage.setItem('wwos.lang', l); } catch { /* storage off: fine */ }
}

