#!/usr/bin/env node
// Scores the reader against samples/truth.json and writes samples/READER-REPORT.md and
// samples/reader-output.json (the readings the demo app shows).
// The number that matters is "ok but wrong": a figure the reader called read that is not right.
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { readDocument } from './read.mjs';
import { normalizeDigits } from './parse.mjs';
import * as tesseract from './engine-tesseract.mjs';
import * as claude from './engine-claude.mjs';
import * as easyocr from './engine-easyocr.mjs';
import * as mix from './engine-mix.mjs';

// node reader/eval.mjs [--hard] [--claude] [id ...]   --hard scores samples/hard-truth.json into HARD-REPORT.md;
// --claude reads with engine-claude.mjs (needs ANTHROPIC_API_KEY) and writes *-claude.md
const root = join(dirname(fileURLToPath(import.meta.url)), '..', 'samples');
const args = process.argv.slice(2);
const hard = args.includes('--hard');
const truth = JSON.parse(await readFile(join(root, hard ? 'hard-truth.json' : 'truth.json'), 'utf8'));
const only = args.filter((a) => !a.startsWith('--'));
const useMix = args.includes('--engine=mix');
const useClaude = useMix || args.includes('--claude') || args.includes('--engine=claude');
const engine = useMix ? mix : useClaude ? claude : args.includes('--engine=easyocr') ? easyocr : tesseract;
const lang = useMix ? `mix ${mix.READERS.join(' + ')}` : useClaude ? `claude ${claude.MODELS.join(' + ')}` : `${engine.name} ${engine.LANG}`;

const asc = (s) => normalizeDigits(String(s ?? ''));
const lev = (a, b) => { const m = a.length, n = b.length; const d = Array.from({ length: m + 1 }, (_, i) => [i, ...Array(n).fill(0)]); for (let j = 1; j <= n; j++) d[0][j] = j;
  for (let i = 1; i <= m; i++) for (let j = 1; j <= n; j++) d[i][j] = Math.min(d[i - 1][j] + 1, d[i][j - 1] + 1, d[i - 1][j - 1] + (a[i - 1] === b[j - 1] ? 0 : 1)); return d[m][n]; };
const sim = (a, b) => { a = a.replace(/\s+/g, ''); b = b.replace(/\s+/g, ''); return 1 - lev(a, b) / Math.max(a.length, b.length, 1); };
const eqNum = (a, b) => a != null && b != null && Math.abs(a - b) < 0.01;

const checks = {
  total: (v, t) => eqNum(v, t.total),
  subtotal: (v, t) => t.vat ? eqNum(v, t.subtotal) : (v == null || eqNum(v, t.subtotal)),
  vat: (v, t) => t.vat ? eqNum(v, t.vat) : (v == null || v === 0),
  date_bs: (v, t) => v === t.date_bs,
  bill_no: (v, t) => asc(v) === asc(t.bill_no),
  pan: (v, t) => t.pan ? asc(v) === t.pan : v == null,
  vendor: (v, t) => v != null && sim(v, t.vendor) >= 0.8,
  method: (v, t) => v === t.method,
};
const FIELDS = Object.keys(checks);
const tally = Object.fromEntries(FIELDS.map((f) => [f, { ok_right: 0, ok_wrong: 0, check_right: 0, check_wrong: 0 }]));
const perBill = [], outputs = {};

for (const t of truth.bills) {
  if (only.length && !only.includes(t.id)) continue;
  const r = await readDocument(join(root, t.file), { kind: 'bill', today: '2026-11-19', engine });
  outputs[t.id] = r;
  const row = { id: t.id, q: t.quality, layout: t.layout, cells: {} };
  for (const f of FIELDS) {
    const fv = r.fields[f]; const right = checks[f](fv?.value ?? null, t);
    const bucket = `${fv?.status === 'ok' ? 'ok' : 'check'}_${right ? 'right' : 'wrong'}`;
    tally[f][bucket]++;
    row.cells[f] = (fv?.status === 'ok' ? '✓' : '?') + (right ? '' : '✗');
  }
  const headRight = r.fields.account_code.value === t.suggested_account; row.head = headRight ? '✓' : (r.fields.account_code.value ? '≠' : '–');
  row.kind = r.fields.kind.value === t.kind ? '✓' : '≠';
  perBill.push(row);
  process.stderr.write(`read ${t.id}\n`);
}
const cashRows = [];
for (const c of truth.cashbooks) {
  if (only.length && !only.includes(c.id)) continue;
  const r = await readDocument(join(root, c.file), { kind: 'cashbook', today: '2026-11-19', engine });
  outputs[c.id] = r;
  const res = { id: c.id, rows: c.rows.length, found: 0, ok_right: 0, ok_wrong: 0, check: 0 };
  for (const tr of c.rows) {
    const got = r.rows.find((x) => x.date_bs === tr.date_bs && (sim(x.particulars, tr.particulars) > 0.5 || x.receipt === tr.receipt || x.payment === tr.payment));
    if (!got) continue;
    res.found++;
    const right = (tr.receipt ? eqNum(got.receipt, tr.receipt) : got.receipt == null) && (tr.payment ? eqNum(got.payment, tr.payment) : got.payment == null);
    if (got.status === 'ok') right ? res.ok_right++ : res.ok_wrong++; else res.check++;
  }
  cashRows.push(res);
  process.stderr.write(`read ${c.id}\n`);
}

const pct = (a, b) => (b ? Math.round((100 * a) / b) + '%' : '–');
let md = hard
  ? `# Reader report — HARD samples (generated by \`node reader/eval.mjs --hard\`, models \`${lang}\`)\n\nScored on ${perBill.length} faded thermal receipts and ${cashRows.length} hand-written cash-book pages in \`samples/hard/\` (made by \`samples/make_hard_samples.py\`). Hand-writing is simulated with hand-lettering fonts, so real cash books will vary more.\n\n`
  : `# Reader report — SAMPLE bills (generated by \`node reader/eval.mjs\`, models \`${lang}\`)\n\nScored on ${perBill.length} fictional bills and ${cashRows.length} cash-book pages in \`samples/\`. These are **clean synthetic images** with simulated phone-photo wear; real Chauthe bills (handwriting, stamps, creases, Nepali fonts we have not seen) will read worse until the reader is tuned on them. Treat every number below as an upper bound.\n\n`;
md += `Legend: ✓ = reader called it "read" (two readings agree and the bill's own sums fit); ? = reader said "check this"; ✗ after it = the figure was wrong.\n\n`;
md += `| bill | photo | layout | ${FIELDS.join(' | ')} | head | kind |\n|${'---|'.repeat(FIELDS.length + 5)}\n`;
for (const r of perBill) md += `| ${r.id} | ${r.q} | ${r.layout} | ${FIELDS.map((f) => r.cells[f]).join(' | ')} | ${r.head} | ${r.kind} |\n`;
md += `\n## Per field\n\n| field | read & right | read but WRONG | check (was right) | check (was wrong) |\n|---|---|---|---|---|\n`;
for (const f of FIELDS) { const t = tally[f]; md += `| ${f} | ${t.ok_right} | **${t.ok_wrong}** | ${t.check_right} | ${t.check_wrong} |\n`; }
md += `\n"read but WRONG" is the number to drive to zero: a figure the app shows as read although it is not right. The person still confirms every entry, but they should never be lulled by a tick.\n`;
if (cashRows.length) {
  md += `\n## Cash-book pages\n\n| page | rows | rows found | read & right | read but WRONG | check |\n|---|---|---|---|---|---|\n`;
  for (const c of cashRows) md += `| ${c.id} | ${c.rows} | ${c.found} | ${c.ok_right} | **${c.ok_wrong}** | ${c.check} |\n`;
}
const wrongTotal = FIELDS.reduce((a, f) => a + tally[f].ok_wrong, 0) + cashRows.reduce((a, c) => a + c.ok_wrong, 0);
const rightTotal = FIELDS.reduce((a, f) => a + tally[f].ok_right, 0) + cashRows.reduce((a, c) => a + c.ok_right, 0);
md += `\n**Read but wrong, all fields: ${wrongTotal}.** Read and right: ${rightTotal}.\n`;
if (useClaude) {
  const pages = perBill.length + cashRows.length;
  const usageAll = useMix ? mix.usage.all : claude.usage;
  const usd = usageAll.reduce((a, u) => a + u.usd, 0);
  const byModel = {};
  for (const u of usageAll) { const m = (byModel[u.model] ??= { calls: 0, in: 0, out: 0, usd: 0 }); m.calls++; m.in += u.input_tokens; m.out += u.output_tokens; m.usd += u.usd; }
  md += `\n## Cost (list prices)\n\n| model | readings | input tokens | output tokens | USD |\n|---|---|---|---|---|\n`;
  for (const [m, v] of Object.entries(byModel)) md += `| ${m} | ${v.calls} | ${v.in} | ${v.out} | ${v.usd.toFixed(4)} |\n`;
  md += `\n**${pages} pages, USD ${usd.toFixed(3)} in all, USD ${(usd / Math.max(pages, 1)).toFixed(4)} per page.**\n`;
}
console.log(md);
if (!only.length && !process.env.EVAL_NO_WRITE) {
  const sfx = useMix ? '-mix' : useClaude ? '-claude' : '';
  if (hard) { await writeFile(join(root, `HARD-REPORT${sfx}.md`), md); if (useClaude) await writeFile(join(root, `hard-output${sfx}.json`), JSON.stringify(outputs, null, 1)); }
  else {
    await writeFile(join(root, `READER-REPORT${sfx}.md`), md);
    await writeFile(join(root, `reader-output${sfx}.json`), JSON.stringify(outputs, null, 1));
  }
}
process.exitCode = wrongTotal ? 1 : 0;
